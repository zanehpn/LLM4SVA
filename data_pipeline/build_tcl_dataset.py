# ---------------------------------------------------------------------------
# GPT-4o-mini generation prompts per level
# ---------------------------------------------------------------------------
LEVEL_PROMPTS = {
    1: ("combinational (no temporal operators; only basic logic like &&, ||, !, "
        "$rose, $fell, $stable, $past). No ## delays, no |-> |=>."),
    2: ("single fixed delay using ##N (constant N) or [*N] or [=N]. "
        "Example: '##2 valid' or 'a [*3]'. May use |-> if combined with ##N only."),
    3: ("variable or ranged delays using ##[a:b], [*a:b], [=a:b] or ##[a:$]. "
        "Must include at least one ranged operator."),
    4: ("sequence operators: |->, |=>, throughout, within, intersect, first_match. "
        "Must use at least one sequence implication operator."),
    5: ("liveness properties using s_eventually, s_until, s_always, until_with, or strong(...). "
        "Must use at least one liveness operator."),
}

GPT_PER_LEVEL = 15  # 15 per level × 5 levels = 75 GPT examples
BATCH_SIZE = 5      # ask for 5 per API call → 3 calls per level = 15 API calls total


def generate_svas_for_level(client: OpenAI, level: int, n: int = BATCH_SIZE) -> list:
    """Ask GPT-4o-mini to generate n SVA examples for the given TCL level."""
    prompt_desc = LEVEL_PROMPTS[level]
    prompt = f"""Generate exactly {n} different SystemVerilog Assertions (SVA) at TCL Level {level}.

TCL Level {level} means: {prompt_desc}

Output ONLY a JSON array of {n} strings, each being a complete SVA assertion.
Use @(posedge clk) as the clock. Use meaningful signal names.
Example format:
["assert property (@(posedge clk) req |-> gnt);", "assert property (@(posedge clk) valid);"]

No markdown, no explanations — only the JSON array."""

    try:
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": "You are an SVA expert. Output only valid JSON arrays."},
                {"role": "user", "content": prompt},
            ],
            temperature=0.7,
            max_tokens=800,
        )
        text = response.choices[0].message.content.strip()
        # Strip markdown fences if present
        if text.startswith("```"):
            text = "\n".join(text.split("\n")[1:])
            if text.endswith("```"):
                text = text[:-3]
        svas = json.loads(text)
        if not isinstance(svas, list):
            return []
        return [str(s).strip() for s in svas if s]
    except Exception as e:
        print(f"  Warning: GPT generation failed for level {level}: {e}")
        return []


def build_dataset():
    os.makedirs(DATA_DIR, exist_ok=True)

    client = OpenAI(api_key=os.environ["OPENAI_API_KEY"])

    dataset = []

    # 1. Add hand-crafted examples (and classify them)
    print("Adding hand-crafted examples...")
    for ex in HAND_CRAFTED:
        level, reason = classify_tcl(ex["sva"])
        dataset.append({
            "id": len(dataset),
            "sva": ex["sva"],
            "tcl_level": level,
            "tcl_reason": reason,
            "expected_level": ex["expected_level"],
            "description": ex["description"],
            "source": "hand",
        })
    print(f"  Added {len(dataset)} hand-crafted examples")

    # 2. Generate GPT examples per level
    api_calls = 0
    for level in [1, 2, 3, 4, 5]:
        level_count = 0
        calls_needed = (GPT_PER_LEVEL + BATCH_SIZE - 1) // BATCH_SIZE
        print(f"Generating L{level} examples ({calls_needed} API calls)...")

        for _ in range(calls_needed):
            if level_count >= GPT_PER_LEVEL:
                break
            svas = generate_svas_for_level(client, level, BATCH_SIZE)
            api_calls += 1
            for sva in svas:
                if level_count >= GPT_PER_LEVEL:
                    break
                classified_level, reason = classify_tcl(sva)
                dataset.append({
                    "id": len(dataset),
                    "sva": sva,
                    "tcl_level": classified_level,
                    "tcl_reason": reason,
                    "expected_level": level,   # what we asked for
                    "description": f"GPT-4o-mini generated L{level}",
                    "source": f"gpt4o-mini-L{level}",
                })
                level_count += 1
            time.sleep(0.3)

        print(f"  L{level}: got {level_count} examples (total API calls so far: {api_calls})")

    print(f"\nTotal API calls used: {api_calls}")
    print(f"Total dataset size: {len(dataset)}")

    with open(OUT_FILE, "w") as f:
        json.dump(dataset, f, indent=2)
    print(f"Saved to {OUT_FILE}")

    # Summary
    from collections import Counter
    level_dist = Counter(ex["tcl_level"] for ex in dataset)
    print("\nClassified TCL distribution:")
    for lv in sorted(level_dist):
        print(f"  L{lv}: {level_dist[lv]}")

    return dataset


if __name__ == "__main__":
    build_dataset()
